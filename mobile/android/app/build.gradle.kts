tasks.whenTaskAdded {
    if (name.contains("Release", ignoreCase = true) &&
        (name.contains("NativeDebugMetadata", ignoreCase = true) ||
            name.contains("DebugSymbols", ignoreCase = true) ||
            name.contains("Strip", ignoreCase = true))) {
        enabled = false
    }
}

